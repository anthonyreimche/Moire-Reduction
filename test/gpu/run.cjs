// Runs moire.webgl.test.ts through a Safelight checkout's WebGL test harness —
// headless Chromium on SwiftShader, the real renderer, the real prepass
// framework and the real coverage bake. The spec is copied into the checkout
// for the run (its harness helpers only resolve from inside) and removed
// afterwards, along with the generated config. Point SAFELIGHT_CORE at the
// checkout; by default `SafeLight` beside this repository's parent folder is
// tried, then beside the repository.
"use strict";

const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const extension = path.resolve(__dirname, "..", "..");
const isCheckout = (dir) => fs.existsSync(path.join(dir, "vitest.webgl.config.ts"));
const candidates = process.env.SAFELIGHT_CORE
  ? [path.resolve(process.env.SAFELIGHT_CORE)]
  : [path.join(extension, "..", "..", "SafeLight"), path.join(extension, "..", "SafeLight")];
const core = candidates.find(isCheckout);
if (!core) {
  console.error(`No Safelight checkout found (tried ${candidates.join(", ")}); set SAFELIGHT_CORE`);
  process.exit(2);
}

const specDir = path.join(core, "src", "rendering", "webgl", "__moire_gpu__");
const specFile = path.join(specDir, "moire.webgl.test.ts");
const configFile = path.join(core, "vitest.moire-gpu.config.ts");

const config = `/// <reference types="vitest/config" />
// Generated by the Moiré Reduction extension's test/gpu/run.cjs — removed after
// the run. Same rig as vitest.webgl.config.ts, plus the extension's sources.
import path from "path";
import { readFileSync } from "fs";
import { defineConfig } from "vite";
import { playwright } from "@vitest/browser-playwright";

const pkg = JSON.parse(readFileSync(path.resolve(__dirname, "package.json"), "utf-8")) as { version: string };
const EXT = ${JSON.stringify(extension)};

export default defineConfig({
  cacheDir: "node_modules/.vite-cache-moire-gpu",
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
      "libraw-wasm": path.resolve(__dirname, "src/raw/vendor/libraw-wasm/index.js"),
      "@moire": path.join(EXT, "src"),
      "@moire-test": path.join(EXT, "test"),
    },
  },
  server: { fs: { allow: [__dirname, EXT] } },
  optimizeDeps: { exclude: ["libraw-wasm"] },
  test: {
    name: "moire-gpu",
    include: ["src/rendering/webgl/__moire_gpu__/*.webgl.test.ts"],
    testTimeout: 300_000,
    browser: {
      enabled: true,
      headless: true,
      provider: playwright(),
      instances: [
        {
          browser: "chromium",
          launch: { args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] },
        },
      ],
    },
  },
});
`;

let status = 1;
try {
  fs.mkdirSync(specDir, { recursive: true });
  fs.copyFileSync(path.join(__dirname, "moire.webgl.test.ts"), specFile);
  fs.writeFileSync(configFile, config);
  const result = spawnSync(
    "npx",
    ["vitest", "run", "--config", path.basename(configFile), "--reporter=verbose"],
    { cwd: core, stdio: "inherit", shell: true },
  );
  status = result.status ?? 1;
} finally {
  fs.rmSync(specDir, { recursive: true, force: true });
  fs.rmSync(configFile, { force: true });
}
process.exit(status);
